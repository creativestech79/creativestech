export function parseContentList(value) {
  return String(value || '')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean)
}

export function parseServiceLines(value) {
  return parseContentList(value).map((line) => {
    const [title, ...description] = line.split('|')
    return { title: title.trim(), description: description.join('|').trim() }
  }).filter((service) => service.title)
}
